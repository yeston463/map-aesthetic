#!/usr/bin/env python3
"""Verify a built map-aesthetic skill ZIP is installable and complete.

Usage:
    python scripts/verify_skill_package.py [path/to/map-aesthetic.zip] [--json]

Checks, in order:
  1. archive integrity and the generated MANIFEST.json
  2. exact file set and per-file SHA-256 / size
  3. SKILL.md frontmatter (name + description)
  4. every local Markdown link resolves inside the package
  5. every script named in the documentation is present and parses
  6. no embedded credential or absolute local path
  7. no cache or generated bytecode

This does not test whether the skill improves an agent's output. It tests that
the thing being handed to an agent is the thing that was reviewed.
"""
from __future__ import annotations

import argparse
import ast
import json
import posixpath
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ZIP = ROOT / ".tmp/releases" / f"map-aesthetic-{json.loads((ROOT / 'package.json').read_text(encoding='utf-8'))['version']}.zip"
MANIFEST_PATH = "map-aesthetic/MANIFEST.json"

LINK = re.compile(r"\]\(([^)]+)\)")
# Only the <skill-dir>/scripts/... form is a promise that the package ships the
# script. Plain `scripts/foo.mjs` mentions repository-level tooling (npm run
# verify:demo, packaging, CI) which is intentionally outside the skill archive.
SCRIPT_REF = re.compile(r"<skill-dir>/scripts/([A-Za-z0-9_.-]+\.(?:py|mjs))")
SECRETS = (
    ("private key block", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("OpenAI-style token", re.compile(r"\bsk-[A-Za-z0-9]{20,}")),
    ("AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Windows absolute path", re.compile(r"[A-Za-z]:[\\/]+Users[\\/]")),
    ("hard-coded API key assignment", re.compile(
        r"(?i)api[_-]?key\s*[:=]\s*['\"][A-Za-z0-9_\-]{20,}['\"]")),
)
TEXT_SUFFIXES = {".md", ".py", ".mjs", ".json", ".yaml", ".yml", ".css", ".js", ".txt"}


class Report:
    def __init__(self) -> None:
        self.checks: list[dict] = []

    def add(self, name: str, ok: bool, detail: str) -> None:
        self.checks.append({"check": name, "ok": ok, "detail": detail})

    @property
    def ok(self) -> bool:
        return all(row["ok"] for row in self.checks)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("zip", nargs="?", type=Path, default=DEFAULT_ZIP)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    archive_path = args.zip.resolve()
    report = Report()

    if not archive_path.is_file():
        report.add("archive-exists", False, f"missing: {archive_path}")
        return finish(report, args.json, archive_path)

    with ZipFile(archive_path) as archive:
        bad_member = archive.testzip()
        report.add("archive-integrity", bad_member is None,
                   "all CRC checks passed" if bad_member is None else f"corrupt member {bad_member}")
        names = set(archive.namelist())
        payload = sorted(name for name in names if name != MANIFEST_PATH)

        if MANIFEST_PATH not in names:
            report.add("manifest-present", False, "MANIFEST.json missing")
            return finish(report, args.json, archive_path)
        manifest = json.loads(archive.read(MANIFEST_PATH))
        report.add("manifest-present", True,
                   f"{manifest.get('skill')} {manifest.get('version')}, "
                   f"{len(manifest.get('files', []))} listed files")

        listed = {entry["path"]: entry for entry in manifest["files"]}
        report.add("manifest-file-set", set(listed) == set(payload),
                   f"listed {len(listed)}, archive payload {len(payload)}")
        mismatches = []
        for name in payload:
            data = archive.read(name)
            entry = listed.get(name)
            if entry is None:
                mismatches.append(f"{name}: not listed")
                continue
            import hashlib
            digest = hashlib.sha256(data).hexdigest()
            if digest != entry["sha256"] or len(data) != entry["size"]:
                mismatches.append(f"{name}: hash/size mismatch")
        report.add("manifest-hashes", not mismatches,
                   "all hashes and sizes match" if not mismatches else "; ".join(mismatches[:5]))

        text = {name: archive.read(name).decode("utf-8", errors="replace")
                for name in payload if Path(name).suffix.lower() in TEXT_SUFFIXES}

        skill_md = text.get("map-aesthetic/SKILL.md", "")
        frontmatter = re.match(r"^---\s*\n(.*?)\n---\s*\n", skill_md, re.DOTALL)
        fields = dict(re.findall(r"^([A-Za-z_-]+):\s*(.+)$", frontmatter.group(1), re.MULTILINE)) if frontmatter else {}
        report.add("frontmatter", bool(frontmatter and fields.get("name") and fields.get("description")),
                   f"name={fields.get('name', 'MISSING')}, description "
                   f"{'present' if fields.get('description') else 'MISSING'}")

        broken_links = []
        for name, body in text.items():
            if not name.endswith(".md"):
                continue
            base = Path(name).parent
            for raw in LINK.findall(body):
                target = raw.strip().split()[0] if raw.strip() else ""
                if not target or target.startswith(("http://", "https://", "mailto:", "#", "<")):
                    continue
                resolved = posixpath.normpath(
                    posixpath.join(base.as_posix(), target.split("#")[0]))
                # A link to a directory is valid if its README exists.
                candidates = {resolved, f"{resolved}/README.md"}
                if not candidates & names:
                    broken_links.append(f"{name}: {target}")
        report.add("local-links", not broken_links,
                   "all local links resolve inside the package" if not broken_links
                   else "; ".join(broken_links[:5]))

        referenced_scripts = set()
        for name, body in text.items():
            if name.endswith(".md"):
                referenced_scripts.update(SCRIPT_REF.findall(body))
        missing_scripts = sorted(f"map-aesthetic/scripts/{name}" for name in referenced_scripts
                                 if f"map-aesthetic/scripts/{name}" not in names)
        shipped_scripts = sorted(name for name in payload
                                 if Path(name).suffix in {".py", ".mjs"})
        report.add("script-files", not missing_scripts and len(shipped_scripts) >= 5,
                   f"{len(referenced_scripts)} referenced, {len(shipped_scripts)} shipped"
                   + (f"; missing {missing_scripts}" if missing_scripts else ""))

        parse_errors = []
        for name in shipped_scripts:
            body = text.get(name)
            if body is None:
                continue
            if name.endswith(".py"):
                try:
                    ast.parse(body, filename=name)
                except SyntaxError as error:
                    parse_errors.append(f"{name}: {error}")
        report.add("python-syntax", not parse_errors,
                   f"{sum(1 for n in shipped_scripts if n.endswith('.py'))} Python scripts parse"
                   if not parse_errors else "; ".join(parse_errors[:3]))

        leaks = []
        for name, body in text.items():
            for label, pattern in SECRETS:
                if pattern.search(body):
                    leaks.append(f"{name}: {label}")
        report.add("no-secrets-or-abs-paths", not leaks,
                   "nothing found" if not leaks else "; ".join(leaks[:5]))

        caches = [name for name in payload
                  if "__pycache__" in name or Path(name).suffix in {".pyc", ".pyo"}]
        report.add("no-caches", not caches,
                   "no generated caches" if not caches else "; ".join(caches[:5]))

        # Node syntax is checked from a temporary extraction: node --check does
        # not execute the script, so this has no side effects.
        mjs = [name for name in shipped_scripts if name.endswith(".mjs")]
        if mjs:
            with tempfile.TemporaryDirectory(prefix="map-skill-verify-") as tmp:
                archive.extractall(tmp, members=mjs)
                node_errors = []
                for name in mjs:
                    result = subprocess.run(["node", "--check", str(Path(tmp) / name)],
                                            capture_output=True, text=True)
                    if result.returncode != 0:
                        node_errors.append(f"{name}: {result.stderr.strip()[:120]}")
                report.add("node-syntax", not node_errors,
                           f"{len(mjs)} JS modules parse" if not node_errors
                           else "; ".join(node_errors[:3]))

    return finish(report, args.json, archive_path)


def finish(report: Report, as_json: bool, archive_path: Path) -> int:
    record = {"archive": str(archive_path), "ok": report.ok, "checks": report.checks}
    out = ROOT / "output" / "package-verification.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if as_json:
        print(json.dumps(record, ensure_ascii=False, indent=2))
    else:
        for row in report.checks:
            print(f"{'PASS' if row['ok'] else 'FAIL'}  {row['check']}: {row['detail']}")
        print(f"\n{'PACKAGE OK' if report.ok else 'PACKAGE INVALID'}  -> {out}")
    return 0 if report.ok else 1


if __name__ == "__main__":
    sys.exit(main())
